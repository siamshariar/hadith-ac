// Names of languages as used inside sentences ("Bản dịch tiếng Anh").
const languageNames = {
  vi: { vi: "tiếng Việt", en: "tiếng Anh", ar: "tiếng Ả Rập" },
  en: { vi: "Vietnamese", en: "English", ar: "Arabic" },
};

export function translate(ui, key, vars) {
  const table = strings[ui] || strings.vi;
  let text = table[key] ?? strings.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.split(`{${name}}`).join(String(value));
    });
  }
  return text;
}

// `fallback` is the API's language object or native name, used for codes
// that have no name in the table above.
export function languageName(ui, code, fallback) {
  const table = languageNames[ui] || languageNames.vi;
  if (table[code]) return table[code];
  if (fallback) return fallback;
  return String(code || "").toUpperCase();
}

// Deterministic thousands separators (toLocaleString can differ between the
// server and the browser and break hydration).
export function formatNumber(value, ui) {
  const number = Number(value);
  if (!Number.isFinite(number)) return "";
  const separator = ui === "vi" ? "." : ",";
  return String(Math.trunc(number)).replace(/\B(?=(\d{3})+(?!\d))/g, separator);
}
