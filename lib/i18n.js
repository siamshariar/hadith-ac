// Every interface catalog, by language code.
export const catalogs = { vi: strings.vi, en: strings.en, ...locales };

export function hasCatalog(code) {
  return Object.prototype.hasOwnProperty.call(catalogs, code);
}

// Names of languages as used inside sentences ("Bản dịch tiếng Anh"). Others come from
