// The interface catalog's string, else the English one, else the key itself.
export function translate(ui, key, vars) {
  const table = catalogs[ui] || catalogs.en;
  let text = table[key] ?? catalogs.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.split(`{${name}}`).join(String(value));
    });
  }
  return text;
}

// `fallback` is the API's language object or native name, used for codes
// that have no name in the table above.
export function languageName(ui, code, fallback) {
  const table = languageNames[ui] || languageNames.en;
  if (table[code]) return table[code];
  if (fallback) return fallback;
  return String(code || "").toUpperCase();
}

// Deterministic thousands separators (toLocaleString can differ between the
// server and the browser and break hydration). Bengali groups the South Asian
// way (1,23,456), in Latin digits like the hadith numbers.
export function formatNumber(value, ui) {
  const number = Number(value);
  if (!Number.isFinite(number)) return "";
  const digits = String(Math.trunc(number));
  if (ui === "bn") {
    const sign = digits.startsWith("-") ? "-" : "";
    const plain = sign ? digits.slice(1) : digits;
    if (plain.length <= 3) return digits;
    const head = plain.slice(0, -3).replace(/\B(?=(\d{2})+(?!\d))/g, ",");
    return `${sign}${head},${plain.slice(-3)}`;
  }
  const separator = ui === "vi" ? "." : ",";
  return digits.replace(/\B(?=(\d{3})+(?!\d))/g, separator);
}

// Languages written right to left. The interface layout is left-to-right only for now,
// so a country whose `ui` is one of these gets the English interface, even once a catalog
// exists, until the layout supports RTL. Content blocks keep their own `dir` either way.
const RTL_LANGUAGES = new Set(["ar", "ur", "ku", "ckb", "fa", "prs", "ps", "sd", "ug", "dv", "he", "yi"]);

export function isRtlLanguage(code) {
  return RTL_LANGUAGES.has(String(code || "").toLowerCase());
}

// The interface a country gets for its `ui` (config/countries.json): that catalog when
// there is one and it is left-to-right, else English.
export function interfaceLanguageFor(ui) {
  return hasCatalog(ui) && !isRtlLanguage(ui) ? ui : "en";
}

